/*
 * DFO Online mods - what the loader should load, in two places:
 *
 *   1. the SERVED registry, <game>/assets/dfo-mods/registry.js - an ES module
 *      the page imports. It is data only:
 *          export const MODS = [
 *            {"id":"skillhud","name":"Skill Tracker","spec":"../dfo-skillhud.js"}
 *          ];
 *      `spec` is relative to `assets/dfo-mods/` (the registry module's own
 *      URL), which is also where boot.js lives, so the loader can import it.
 *
 *   2. the WORKSPACE manifest, modloader/mods.json - which installers to run
 *      on `sync.mjs` (autosync after a game update):
 *          {"mods":[{"id":"skillhud","name":"Skill Tracker","dir":"../skillhud-mod"}]}
 *
 * `dir` is relative to modloader/. Entries are merged by id, so independent
 * mod installers never clobber each other.
 */
'use strict';

import fs from 'node:fs';
import path from 'node:path';
import { writeJsonAtomic } from './game.mjs';
import { MODLOADER_ROOT } from './store.mjs';

export const REGISTRY_REL = 'assets/dfo-mods/registry.js';
export const REGISTRY_DIR = path.dirname(REGISTRY_REL);
export const MANIFEST_FILE = path.join(MODLOADER_ROOT, 'mods.json');

const HEADER = '// generated by the DFO modloader installers - one entry per installed mod\n';
const clean = (m) => (m && typeof m.id === 'string' && typeof m.spec === 'string' && m.id && m.spec
  ? { id: m.id, name: typeof m.name === 'string' && m.name ? m.name : m.id, spec: m.spec }
  : null);

/** Parse the served registry module without executing it. */
export function parseRegistry(text) {
  if (typeof text !== 'string') return [];
  const m = /export const MODS\s*=\s*(\[[\s\S]*?\]);/.exec(text);
  if (!m) return [];
  try {
    const list = JSON.parse(m[1]);
    return Array.isArray(list) ? list.map(clean).filter(Boolean) : [];
  } catch { return []; }
}
export function renderRegistry(list) {
  const mods = list.map(clean).filter(Boolean).sort((a, b) => a.id.localeCompare(b.id));
  return `${HEADER}export const MODS = ${JSON.stringify(mods, null, 0)};\n`;
}

export function readRegistry(store) {
  const got = store.read(REGISTRY_REL);
  return got ? parseRegistry(got.bytes.toString('utf8')) : [];
}
export function writeRegistry(store, list) {
  store.write(REGISTRY_REL, Buffer.from(renderRegistry(list), 'utf8'), { owned: true });
}
/** Add or replace one mod's entry, preserving every other entry. */
export function upsertRegistry(store, entry) {
  const e = clean(entry);
  if (!e) throw new Error('registry entry needs an id and a spec');
  const list = readRegistry(store).filter((m) => m.id !== e.id);
  list.push(e);
  writeRegistry(store, list);
  return list;
}
export function removeRegistry(store, id) {
  const list = readRegistry(store).filter((m) => m.id !== id);
  writeRegistry(store, list);
  return list;
}

/* ---------------------------------------------------------- workspace manifest */
export function readManifest() {
  try {
    const m = JSON.parse(fs.readFileSync(MANIFEST_FILE, 'utf8'));
    return Array.isArray(m?.mods) ? m.mods.filter((e) => e && typeof e.id === 'string' && typeof e.dir === 'string') : [];
  } catch { return []; }
}
export function writeManifest(list) {
  fs.mkdirSync(path.dirname(MANIFEST_FILE), { recursive: true });
  writeJsonAtomic(MANIFEST_FILE, {
    mods: list
      .filter((e) => e && e.id && e.dir)
      .map((e) => ({ id: e.id, name: e.name || e.id, dir: e.dir }))
      .sort((a, b) => a.id.localeCompare(b.id)),
  });
}
export function upsertManifest(entry) {
  writeManifest([...readManifest().filter((m) => m.id !== entry.id), entry]);
}
export function removeManifest(id) {
  writeManifest(readManifest().filter((m) => m.id !== id));
}
/** A manifest entry's absolute installer directory. */
export const manifestDir = (entry) => path.resolve(MODLOADER_ROOT, entry.dir);
